import numpy as np
import matplotlib.pyplot as plt

# Definir la función
def f(x):
    return np.exp(-x) - x

# Método de bisección
def biseccion(a, b, tol=1e-5, max_iter=100):
    if f(a) * f(b) > 0:
        raise ValueError("El intervalo no contiene una raíz.")

    iteraciones = []
    errores = []
    fa = f(a)

    for i in range(max_iter):
        c = (a + b) / 2
        fc = f(c)

        iteraciones.append((i+1, c, fc))
        error = abs(b - a) / 2
        errores.append(error)

        if error < tol or abs(fc) < tol:
            break

        if fa * fc < 0:
            b = c
        else:
            a = c
            fa = fc

    return iteraciones, errores, c

# Definir intervalo y ejecutar el método
