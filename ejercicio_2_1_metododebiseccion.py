import numpy as np
import matplotlib.pyplot as plt

# Definir la función
def f(x):
    return x**3 - 4*x - 9

# Método de bisección
def biseccion(a, b, tol=1e-5, max_iter=100):
    if f(a) * f(b) >= 0:
        print("El método de bisección no es aplicable en este intervalo.")
        return None, None

    iteraciones = []
    errores = []

    for i in range(max_iter):
        c = (a + b) / 2
        iteraciones.append((i+1, c, f(c)))
        error = abs(b - a) / 2
        errores.append(error)

        if abs(f(c)) < tol or error < tol:
            return c, iteraciones, errores

        if f(c) * f(a) < 0:
            b = c
        else:
            a = c

    return c, iteraciones, errores

# Intervalo y tolerancia
a, b = 2, 3
tolerancia = 1e-5

# Llamar al método
raiz, iteraciones, errores = biseccion(a, b, tolerancia)

# Imprimir los resultados
print("Iteración | x_n      | f(x_n)")
print("--------------------------------")
for it in iteraciones:
    print(f"{it[0]:9d} | {it[1]:.6f} | {it[2]:.6e}")

print(f"\nAproximación de la raíz: {raiz:.6f}")

# Graficar la función con la raíz encontrada
x_vals = np.linspace(1, 4, 400)
